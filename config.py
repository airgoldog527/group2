
# ============================================================
# config.py — 專案通訊共用設定
# ============================================================


# ------------------------------
# 網路設定
# ------------------------------

# 本機（接收端／伺服器）的 IP 位址
# 請依照各台電腦的實際網路 IP 位址填寫
HOST_IP = "0.0.0.0"

# 對方（傳送端／客戶端）的 IP 位址
# 請填寫與本機進行 TCP 通訊的對方電腦 IP 位址
CLIENT_IP = "127.0.0.1"

# TCP 通訊使用的連接埠
# 傳送端與接收端必須使用相同的 Port
TCP_PORT = 5000

# 電腦 C：原始影像接收端
VIDEO_TARGET_IP = "192.168.1.4"
VIDEO_TARGET_PORT = 5000

# 電腦 C：YOLO 文字接收端
TARGET_IP = "192.168.1.4"
TARGET_PORT = 5001

# ------------------------------
# 封包基本設定
# ------------------------------

# 封包識別碼，用來確認收到的資料是否符合本專案的封包格式
MAGIC = 0x4652414D

# 通訊協定版本，用來識別目前使用的封包格式版本
VERSION = 1

# 封包標頭格式：
# < 代表使用小端序（Little Endian）
# I 代表 4 位元組無號整數（Unsigned Integer）
# B 代表 1 位元組無號整數（Unsigned Byte）
# H 代表 2 位元組無號整數（Unsigned Short）
HEADER_FORMAT = "<IBBIHHBI"

# 封包標頭的長度，單位為位元組（Byte）
HEADER_SIZE = 19

# CRC32 檢查碼的長度，單位為位元組（Byte）
# 用來檢查封包資料是否在傳輸過程中發生錯誤
CRC_SIZE = 4


# ------------------------------
# 封包類型
# ------------------------------

# 影像封包，用來傳送影像資料
TYPE_FRAME = 0x01

# 文字封包，用來傳送分析結果或其他文字資訊
TYPE_TEXT = 0x02


# ------------------------------
# 影像像素格式
# ------------------------------

# 灰階影像（Gray8）
# 每個像素使用 1 位元組儲存灰階數值
PIXEL_FORMAT_GRAY8 = 0x01

# BGR 彩色影像（BGR24）
# 每個像素使用 3 位元組，依序儲存藍、綠、紅三個通道
PIXEL_FORMAT_BGR24 = 0x02

# RGB 彩色影像（RGB24）
# 每個像素使用 3 位元組，依序儲存紅、綠、藍三個通道
PIXEL_FORMAT_RGB24 = 0x03


# ------------------------------
# 影像與封包限制
# ------------------------------

# 單張影像允許的最大寬度，單位為像素（Pixel）
MAX_WIDTH = 4096

# 單張影像允許的最大高度，單位為像素（Pixel）
MAX_HEIGHT = 4096

# 單一封包允許的最大資料長度，單位為位元組（Byte）
# 64 * 1024 * 1024 代表 64 MB
MAX_PAYLOAD_SIZE = 64 * 1024 * 1024

# 影格編號允許的最大值
# 使用 32 位元無號整數，供連續影片傳輸時識別每一張影格
MAX_FRAME_ID = 0xFFFFFFFF


# ------------------------------
# 影像傳輸速度設定
# ------------------------------

# RGB 彩色影像每秒傳送的影格數（Frames Per Second）
RGB_FPS = 10

# 灰階影像每秒傳送的影格數（Frames Per Second）
GRAY_FPS = 10

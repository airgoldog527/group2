# ============================================================
# config.py — 專案通訊共用設定
# ============================================================

# ------------------------------
# 網路設定
# ------------------------------

# 本機（接收端／伺服器）的 IP 位址，最後一段自行填寫
HOST_IP = "192.168.1."

# 對方（傳送端／客戶端）的 IP 位址，最後一段自行填寫
CLIENT_IP = "192.168.1."

# TCP 通訊使用的連接埠
TCP_PORT = 5000


# ------------------------------
# 封包基本設定
# ------------------------------

# 封包識別碼，用來確認收到的資料是否符合本專案的格式
MAGIC = 0x4652414D

# 通訊協定版本
VERSION = 1

# 封包標頭格式：
# < 代表使用小端序
# I 代表 4 位元組無號整數
# B 代表 1 位元組無號整數
# H 代表 2 位元組無號整數
HEADER_FORMAT = "<IBBIHHBI"

# 封包標頭的長度，單位為位元組
HEADER_SIZE = 19

# CRC32 檢查碼的長度，單位為位元組
CRC_SIZE = 4


# ------------------------------
# 封包類型
# ------------------------------

# 影像封包
TYPE_FRAME = 0x01

# 文字封包
TYPE_TEXT = 0x02


# ------------------------------
# 影像像素格式
# ------------------------------

# 灰階影像：每個像素使用 1 位元組
PIXEL_FORMAT_GRAY8 = 0x01

# BGR 彩色影像：每個像素依序排列藍、綠、紅三個通道
PIXEL_FORMAT_BGR24 = 0x02

# RGB 彩色影像：每個像素依序排列紅、綠、藍三個通道
PIXEL_FORMAT_RGB24 = 0x03


# ------------------------------
# 影像與封包限制
# ------------------------------

# 單張影像允許的最大寬度，單位為像素
MAX_WIDTH = 4096

# 單張影像允許的最大高度，單位為像素
MAX_HEIGHT = 4096

# 單一封包允許的最大資料長度，單位為位元組
MAX_PAYLOAD_SIZE = 64 * 1024 * 1024

# 影格編號允許的最大值，供連續影片傳輸使用
MAX_FRAME_ID = 0xFFFFFFFF